
import json
import os
import re
import boto3

BOT_ID = os.environ["BOT_ID"]
BOT_ALIAS_ID = os.environ["BOT_ALIAS_ID"]
LOCALE_ID = os.environ.get("LOCALE_ID", "en_US")

lex_runtime = boto3.client("lexv2-runtime", region_name="ap-southeast-1")


def response(status_code, body):
    return {
        "statusCode": status_code,
        "headers": {
            "Content-Type": "application/json",
            "Cache-Control": "no-store"
        },
        "body": json.dumps(body)
    }


def lambda_handler(event, context):
    try:
        body = event.get("body", {})
        if isinstance(body, str):
            body = json.loads(body) if body else {}

        message = body.get("message", "")
        session_id = body.get("sessionId", "")

        if not isinstance(message, str) or not message.strip():
            return response(400, {"error": "A message is required."})

        if len(message) > 1000:
            return response(400, {"error": "Message is too long."})

        # Use a random session ID generated by the client.
        # Accept only safe characters and limit its length.

        if not isinstance(session_id, str) or not re.fullmatch(
            r"[A-Za-z0-9_-]{1,100}", session_id
        ):
            return response(400, {"error": "Invalid session ID."})

        result = lex_runtime.recognize_text(
            botId=BOT_ID,
            botAliasId=BOT_ALIAS_ID,
            localeId=LOCALE_ID,
            sessionId=session_id,
            text=message.strip()
        )

        messages = [
            item.get("content", "")
            for item in result.get("messages", [])
            if item.get("contentType") == "PlainText"
        ]

        intent = (
            result.get("sessionState", {})
            .get("intent", {})
            .get("name", "")
        )

        return response(200, {
            "messages": messages,
            "intent": intent,
            "sessionId": session_id
        })

    except Exception as exc:
        print("Lex proxy error:", type(exc).__name__, str(exc))
        return response(500, {
            "error": "Sorry, the chatbot is temporarily unavailable."
        })
